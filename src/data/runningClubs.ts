/** Champ du club interrogé par chaque groupe de filtres. */
export const FILTER_FIELDS: Record<string, keyof RunningClub> = {
  city: "city",
  day: "days",
  moment: "moments",
  session: "sessions",
  level: "levels",
  distance: "distances",
  audience: "audiences",
  vibe: "vibes",
};

/** OU à l'intérieur d'un groupe, ET entre les groupes. */
export function filterClubs(
  clubs: readonly RunningClub[],
  selected: Record<string, string[]>,
): RunningClub[] {
  const active = Object.entries(selected).filter(([, values]) => values.length > 0);
  if (active.length === 0) return [...clubs];

  return clubs.filter((club) =>
    active.every(([groupKey, values]) => {
      const field = FILTER_FIELDS[groupKey];
      if (!field) return true;
      const clubValue = club[field];
      return Array.isArray(clubValue)
        ? clubValue.some((v) => values.includes(v as string))
        : values.includes(clubValue as string);
    }),
  );
}
